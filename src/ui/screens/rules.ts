// Сжатые правила режима «Классика».
import { Rank } from '../../core/types';
import { setMood } from '../../render/background';
import { open } from '../nav';
import { btn, h } from '../dom';
import { pieceIcon } from '../widgets';

export function rulesScreen(root: HTMLElement) {
  setMood('menu');
  const block = (title: string, ...body: (Node | string)[]) => h('section', { class: 'rule-block slab' }, h('div', { class: 'h-label' }, title), ...body);
  const piece = (r: Rank, name: string, move: string, atk: string) =>
    h('div', { class: 'rule-piece' }, pieceIcon(r, 'red', 3), h('div', {}, h('b', {}, name), h('div', {}, `Ход: ${move}`), h('div', {}, `Атака: ${atk}`)));
  root.append(
    h(
      'div',
      { class: 'page' },
      h('div', { class: 'page-head' }, h('h1', {}, 'Правила · Классика'), h('div', { class: 'page-sub' }, 'Уничтожьте все фигуры соперника'), btn('В меню', () => open('menu'))),
      h(
        'div',
        { class: 'rules-grid' },
        block(
          'Поле и армия',
          h('p', {}, 'Поле 12×12. У каждого 12 треугольников, 6 квадратов и 3 круга. Расстановка — скрытно, в своих первых трёх рядах. Цвета и первый ход — случайно.'),
        ),
        block(
          'Фигуры',
          piece(Rank.Triangle, 'Треугольник', '1 вперёд', '1 вперёд или по диагонали вперёд'),
          piece(Rank.Square, 'Квадрат', '1–3 вперёд, по диагонали вперёд, вбок', 'те же направления, 1–3'),
          piece(Rank.Circle, 'Круг', '1–5 в любую сторону', '1–5 в любую сторону'),
          h('p', { class: 'muted' }, 'Промежуточные клетки должны быть свободны.'),
        ),
        block(
          'Ход',
          h('p', {}, '5 очков действий. Перемещение — 1 очко. Атака уничтожает фигуру, занимает её клетку и сжигает все оставшиеся очки. Каждая фигура действует не больше одного раза за ход.'),
          h('p', {}, 'Завершить ход вручную можно после хотя бы одного действия. 5 минут на ход, 60 минут на партию. Если по карте выбирает соперник, ваши часы стоят, а у него 15 секунд на весь выбор — иначе выбор делается случайно.'),
        ),
        block(
          'Повышение',
          h('p', {}, 'Дошёл до последнего ряда соперника: треугольник → квадрат, квадрат → круг. Новая фигура ставится в стартовую зону, а если там нет места — в 4-й ряд или ближайший следующий ряд со свободной клеткой. Если клетка под ударом — повышение откладывается до вашего следующего хода.'),
        ),
        block(
          'Карма',
          h('p', {}, 'Каждый 7-й собственный ход вы получаете Карту Кармы из колоды матча (21 карта). Карты открытые. «После получения» — разыгрываются сразу; «в течение периода» — до конца текущего Периода (7 ходов).'),
        ),
        block('Ничья', h('p', {}, 'У каждого по одной фигуре одного ранга или по две с одинаковым набором — и три Периода Кармы без изменений.')),
      ),
    ),
  );
}
